/**
 * Client-Side Screenplay and Production Bible TXT Exporter
 * Generates an industry-formatted screenplay script and comprehensive production bible
 */

export function exportProjectToTxt(projectData) {
  if (!projectData) {
    alert('No active project found to export.');
    return;
  }

  const proj = projectData.project || {};
  const title = (proj.title || 'UNTITLED_SCREENPLAY').toUpperCase();
  const filename = `${title.replace(/[^a-zA-Z0-9_-]/g, '_')}_Production_Bible.txt`;

  const lines = [];
  const divider = '='.repeat(78);
  const subDivider = '-'.repeat(78);

  // 1. COVER / TITLE PAGE
  lines.push(divider);
  lines.push('');
  lines.push(`                             ${title}`);
  lines.push('');
  lines.push('                   A SCREENPLAY PRODUCTION BIBLE');
  lines.push('                  Generated by CineDirector AI');
  lines.push('');
  lines.push(`   Genre:             ${proj.genre || 'N/A'}`);
  lines.push(`   Tone / Mood:       ${proj.tone || 'N/A'}`);
  lines.push(`   Target Runtime:    ${proj.runtimeMinutes || 110} Minutes`);
  lines.push(`   Primary Language:  ${proj.language || 'English'}`);
  lines.push(`   Date of Export:    ${new Date().toLocaleDateString()}`);
  lines.push('');
  lines.push(divider);
  lines.push('');
  lines.push('LOGLINE:');
  lines.push(`  "${proj.logline || 'N/A'}"`);
  lines.push('');
  lines.push('THEMATIC CORE:');
  lines.push(`  "${proj.theme || 'N/A'}"`);
  lines.push('');
  lines.push('');

  // 2. THREE-ACT DRAMATIC STRUCTURE
  if (projectData.storyStructure) {
    const ss = projectData.storyStructure;
    lines.push(divider);
    lines.push('SECTION I: THREE-ACT DRAMATIC STRUCTURE');
    lines.push(divider);
    lines.push('');

    if (ss.actOne) {
      lines.push('--- ACT I: THE ORDINARY WORLD & CATALYST ---');
      lines.push(`Summary:            ${ss.actOne.summary || 'N/A'}`);
      lines.push(`Inciting Incident:  ${ss.actOne.incitingIncident || 'N/A'}`);
      lines.push(`Turning Point 1:    ${ss.actOne.turningPoint || 'N/A'}`);
      lines.push('');
    }

    if (ss.actTwo) {
      lines.push('--- ACT II: RISING TENSION & MIDPOINT CRISIS ---');
      lines.push(`Summary:            ${ss.actTwo.summary || 'N/A'}`);
      lines.push(`Midpoint Shift:     ${ss.actTwo.midpoint || 'N/A'}`);
      lines.push(`Core Conflict:      ${ss.actTwo.majorConflict || 'N/A'}`);
      lines.push(`Turning Point 2:    ${ss.actTwo.turningPoint || 'N/A'}`);
      lines.push('');
    }

    if (ss.actThree) {
      lines.push('--- ACT III: CLIMAX & RESOLUTION ---');
      lines.push(`Summary:            ${ss.actThree.summary || 'N/A'}`);
      lines.push(`The Climax:         ${ss.actThree.climax || 'N/A'}`);
      lines.push(`Resolution:         ${ss.actThree.resolution || 'N/A'}`);
      lines.push('');
    }
  }

  // 3. CHARACTER PROFILES
  if (Array.isArray(projectData.characters) && projectData.characters.length > 0) {
    lines.push(divider);
    lines.push('SECTION II: CHARACTER DOSSIERS & CASTING BIBLE');
    lines.push(divider);
    lines.push('');

    projectData.characters.forEach((char, idx) => {
      lines.push(`[${idx + 1}] ${(char.name || 'UNNAMED').toUpperCase()} (${char.role || 'Role N/A'})`);
      lines.push(`    Age:            ${char.age || 'N/A'}`);
      lines.push(`    Personality:    ${char.personality || 'N/A'}`);
      lines.push(`    Core Goal:      ${char.motivation || 'N/A'}`);
      lines.push(`    Backstory:      ${char.backstory || 'N/A'}`);
      lines.push(`    Dramatic Arc:   ${char.characterArc || 'N/A'}`);
      lines.push(`    Physicality:    ${char.physicalDescription || 'N/A'}`);
      lines.push(`    Costume Notes:  ${char.costumeNotes || 'N/A'}`);
      lines.push('');
    });
  }

  // 4. SCREENPLAY SCENES (HOLLYWOOD STANDARD FORMATTING)
  if (Array.isArray(projectData.scenes) && projectData.scenes.length > 0) {
    lines.push(divider);
    lines.push('SECTION III: SCREENPLAY SCRIPT');
    lines.push(divider);
    lines.push('');

    projectData.scenes.forEach(scene => {
      lines.push(`SCENE ${scene.sceneNumber || ''}`);
      lines.push((scene.heading || 'SCENE HEADING').toUpperCase());
      lines.push('');

      if (scene.action) {
        // Wrap action lines
        lines.push(scene.action);
        lines.push('');
      }

      if (Array.isArray(scene.dialogue)) {
        scene.dialogue.forEach(dia => {
          // Standard Hollywood screenplay indentation
          const charName = (dia.character || 'CHARACTER').toUpperCase();
          lines.push(`                        ${charName}`);
          if (dia.direction) {
            lines.push(`                     ${dia.direction}`);
          }
          if (dia.line) {
            lines.push(`            ${dia.line}`);
          }
          lines.push('');
        });
      }

      if (scene.transition) {
        lines.push(`                                                      ${scene.transition}`);
        lines.push('');
      }

      lines.push(subDivider);
      lines.push('');
    });
  }

  // 5. DIRECTOR'S SHOT LISTS
  if (Array.isArray(projectData.shotLists) && projectData.shotLists.length > 0) {
    lines.push(divider);
    lines.push('SECTION IV: DIRECTOR\'S CINEMATOGRAPHY SHOT LISTS');
    lines.push(divider);
    lines.push('');

    projectData.shotLists.forEach(sl => {
      lines.push(`=== SHOT BREAKDOWN: SCENE ${sl.sceneNumber} ===`);
      if (Array.isArray(sl.shots)) {
        sl.shots.forEach(shot => {
          lines.push(`  SHOT #${shot.shotNumber}: [${shot.shotType || 'MS'}]`);
          lines.push(`    Camera Movement:  ${shot.cameraMovement || 'Static'}`);
          lines.push(`    Suggested Lens:   ${shot.lens || '35mm'}`);
          lines.push(`    Framing & Angle:  ${shot.framing || 'Eye level'}`);
          lines.push(`    Lighting Setup:   ${shot.lighting || 'Natural'}`);
          lines.push(`    Composition:      ${shot.visualDescription || 'N/A'}`);
          lines.push(`    Director Notes:   ${shot.directorNotes || 'N/A'}`);
          lines.push('');
        });
      }
      lines.push('');
    });
  }

  // 6. MIDJOURNEY IMAGE PROMPTS
  if (Array.isArray(projectData.imagePrompts) && projectData.imagePrompts.length > 0) {
    lines.push(divider);
    lines.push('SECTION V: MIDJOURNEY CONCEPT ART PROMPTS');
    lines.push(divider);
    lines.push('');

    projectData.imagePrompts.forEach((ip, idx) => {
      lines.push(`PROMPT ${idx + 1} (Scene ${ip.sceneNumber || 'General'} - ${ip.purpose || 'Concept'}):`);
      lines.push(`  PROMPT:`);
      lines.push(`    /imagine prompt: ${ip.prompt || 'N/A'}`);
      if (ip.negativePrompt) {
        lines.push(`  NEGATIVE PROMPT:`);
        lines.push(`    --no ${ip.negativePrompt}`);
      }
      lines.push('');
    });
  }

  // 7. RUNWAY VIDEO PROMPTS
  if (Array.isArray(projectData.videoPrompts) && projectData.videoPrompts.length > 0) {
    lines.push(divider);
    lines.push('SECTION VI: RUNWAY VIDEO GENERATION PROMPTS');
    lines.push(divider);
    lines.push('');

    projectData.videoPrompts.forEach((vp, idx) => {
      lines.push(`VIDEO CUE ${idx + 1} (Scene ${vp.sceneNumber || 'General'} - Duration: ${vp.durationSeconds || 8}s):`);
      lines.push(`  Prompt:         ${vp.prompt || 'N/A'}`);
      lines.push(`  Camera Motion:  ${vp.cameraMotion || 'N/A'}`);
      lines.push(`  Visual Texture: ${vp.visualStyle || 'N/A'}`);
      lines.push('');
    });
  }

  // 8. AUDIO & SOUND DESIGN
  if (Array.isArray(projectData.audioDesign) && projectData.audioDesign.length > 0) {
    lines.push(divider);
    lines.push('SECTION VII: SOUND DESIGN & ACOUSTIC LANDSCAPE');
    lines.push(divider);
    lines.push('');

    projectData.audioDesign.forEach(ad => {
      lines.push(`SCENE ${ad.sceneNumber} AUDIO CUES:`);
      lines.push(`  Spatial Ambience:  ${ad.ambience || 'N/A'}`);
      if (Array.isArray(ad.soundEffects) && ad.soundEffects.length > 0) {
        lines.push(`  Foley Sound Effects:`);
        ad.soundEffects.forEach(sfx => lines.push(`    * ${sfx}`));
      }
      lines.push(`  Music Score Cue:   ${ad.musicCue || 'N/A'}`);
      lines.push(`  Emotional Subtext: ${ad.emotionalIntent || 'N/A'}`);
      lines.push('');
    });
  }

  // 9. PRODUCTION SUMMARY
  if (projectData.productionSummary) {
    const ps = projectData.productionSummary;
    lines.push(divider);
    lines.push('SECTION VIII: PRODUCTION SUMMARY & DIRECTORIAL VISION');
    lines.push(divider);
    lines.push('');
    lines.push(`Visual Aesthetic Statement:`);
    lines.push(`  ${ps.visualStyle || 'N/A'}`);
    lines.push('');

    if (Array.isArray(ps.colorPalette) && ps.colorPalette.length > 0) {
      lines.push(`Curated Film Color Palette:`);
      ps.colorPalette.forEach(col => lines.push(`  [X] ${col}`));
      lines.push('');
    }

    if (Array.isArray(ps.productionChallenges) && ps.productionChallenges.length > 0) {
      lines.push(`Technical & Production Hurdles:`);
      ps.productionChallenges.forEach(ch => lines.push(`  * ${ch}`));
      lines.push('');
    }

    if (Array.isArray(ps.keyCreativeDecisions) && ps.keyCreativeDecisions.length > 0) {
      lines.push(`Key Directorial Choices:`);
      ps.keyCreativeDecisions.forEach(kcd => lines.push(`  * ${kcd}`));
      lines.push('');
    }
  }

  lines.push(divider);
  lines.push('End of Production Bible. CineDirector AI (c) 2026.');
  lines.push(divider);

  const fileContent = lines.join('\n');
  const blob = new Blob([fileContent], { type: 'text/plain;charset=utf-8' });
  const url = URL.createObjectURL(blob);

  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);

  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
